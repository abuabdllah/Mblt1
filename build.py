def faq_html(faqs):
    if not faqs: return ""
    items = "".join(f"<details><summary>{esc(q)}</summary><p>{a}</p></details>" for q, a in faqs)
    return f'<div class="faq">{items}</div>'

def faq_schema(faqs):
    import re
    return {"@type":"FAQPage","mainEntity":[{"@type":"Question","name":q,
      "acceptedAnswer":{"@type":"Answer","text":re.sub("<[^>]+>","",a)}} for q,a in faqs]}

